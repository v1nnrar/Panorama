#!/usr/bin/env python
"""Rank capacity-study options and write 06_reports/capacity_study.md (+ aerial contact sheet).

Score (higher = better), used by the improvement loop (LOOP.md section D):
  * hard rules (02_regulations/rules.yaml: height, storeys, PSP §21, §22, parking) must all PASS, else score = 0
  * quality floors (design proxies): daylight_proxy_fail_ratio ≤ 0.15, courtyard sun ≥ 2.0 h on 21 March,
    built-up ratio ≤ 0.45 — each miss subtracts 10 % of the score
  * score = above-ground GFA in thousands of m² × (1 − penalties)
The client's existing scheme is listed as the baseline (scored the same way).

Usage: .venv/bin/python tools/score_options.py
"""
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FLOORS = {"daylight_proxy_fail_ratio": ("≤", 0.15), "courtyard_sun_hours_mean_mar21": ("≥", 2.0), "built_up_ratio": ("≤", 0.45)}


def score(m, comp):
    hard_fail = [r["label"] for r in comp if r["status"] == "FAIL"]
    misses = []
    for k, (op, lim) in FLOORS.items():
        v = m.get(k)
        if v is None or (op == "≤" and v > lim) or (op == "≥" and v < lim):
            misses.append(f"{k} {v} (want {op} {lim})")
    s = 0.0 if hard_fail else round(m["gfa_m2"] / 1000 * (1 - 0.1 * len(misses)), 2)
    return s, hard_fail, misses


def main():
    rows = []
    entries = [("Client scheme (baseline)", ROOT / "03_existing")]
    entries += [(p.parent.name, p.parent) for p in sorted((ROOT / "04_proposed/options").glob("*/params.yaml"))]
    for name, d in entries:
        f = d / "model" / "metrics.json"
        if not f.exists():
            continue
        data = json.loads(f.read_text())
        m, comp = data["metrics"], data["compliance"]
        s, hard, misses = score(m, comp)
        title = name
        pf = d / "params.yaml"
        if pf.exists() and name != "Client scheme (baseline)":
            first = pf.read_text().splitlines()[0].lstrip("# ").strip()
            title = first
        levels = None
        if pf.exists():   # basement levels = storeys of the below-ground building(s) (D6)
            import yaml
            for b in yaml.safe_load(pf.read_text()).get("buildings", []):
                if float(b.get("ground_elevation", 0)) < 0:
                    levels = sum(int(g.get("count", 1)) for g in b["storeys"])
        rows.append({"key": name, "title": title, "score": s, "hard_fail": hard, "misses": misses, "m": m, "dir": d,
                     "levels": levels})
    rows.sort(key=lambda r: -r["score"])
    L = ["# Capacity study — options vs the client scheme", "",
         "Generated by `tools/score_options.py` from each scheme's `model/metrics.json`. Rules: `02_regulations/rules.yaml`",
         "(Metropolitan Plan + Prague building regulations). Score = above-ground GFA (thousand m²) if every hard rule",
         "passes, minus 10 % per missed quality floor (daylight proxy ≤ 0.15 failing, courtyard sun ≥ 2 h on 21 March,",
         "built-up ratio ≤ 0.45). Estimates: hotel 62 % net / 34 m² per key; flats 78 % net / 65 m²; parking zone 02 ASSUMED.",
         "Basement levels: fewest 3.5 m levels whose capacity covers the PSP §25 minimum (`basement_levels: auto`).", "",
         "| Rank | Scheme | Score | GFA above ground m² | FAR | Max height m | Storeys | Hotel keys | Flats | Parking need / capacity | Basement levels | §21 failing windows | Daylight proxy fail | Courtyard sun h | Built-up |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        m = r["m"]
        L.append(f"| {i} | {r['title']} | **{r['score']}** | {m['gfa_m2']:,.0f} | {m['plot_ratio_far']} | {m['height_top_of_parapet_m']} | "
                 f"{m['storeys_above_ground']} | {m.get('hotel_keys_est')} | {m.get('flats_est')} | "
                 f"{m.get('parking_required_min')} / {m.get('parking_capacity_est')} | {r['levels']} | {m.get('psp21_windows_failing')} | "
                 f"{m.get('daylight_proxy_fail_ratio')} | {m.get('courtyard_sun_hours_mean_mar21')} | {m['built_up_ratio']} |")
    L += ["", "## Notes per scheme", ""]
    for r in rows:
        L.append(f"- **{r['title']}** — " + ("all hard rules pass" if not r["hard_fail"] else "FAILS: " + "; ".join(r["hard_fail"]))
                 + ("; quality misses: " + "; ".join(r["misses"]) if r["misses"] else "; quality floors met")
                 + (f"; §21 neighbours: {r['m'].get('psp21_failing_neighbours')}" if r["m"].get("psp21_windows_failing") else ""))
    out = ROOT / "06_reports" / "capacity_study.md"
    out.write_text("\n".join(L) + "\n")
    # contact sheet of aerials
    ims = []
    for r in rows:
        for cand in ("render_aerial_S.png", "render_aerial_S_like_render000.png"):
            p = r["dir"] / "model" / cand
            if p.exists():
                ims.append((r, Image.open(p).convert("RGB").resize((640, 452))))
                break
    if ims:
        cols = 2
        W, H = 640, 452 + 40
        sheet = Image.new("RGB", (W * cols, H * ((len(ims) + 1) // cols)), "white")
        dr = ImageDraw.Draw(sheet)
        try:
            font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 18)
        except Exception:
            font = None
        for k, (r, im) in enumerate(ims):
            x, y = (k % cols) * W, (k // cols) * H
            sheet.paste(im, (x, y + 40))
            dr.text((x + 10, y + 10), f"{r['title'][:60]}  |  score {r['score']}  |  {r['m']['gfa_m2']:,.0f} m²", fill="black", font=font)
        sheet.save(ROOT / "06_reports" / "capacity_study_aerials.jpg", quality=88)
    print(out.read_text())


if __name__ == "__main__":
    main()
